import { defineConfig } from 'vite'
import react from '@vitejs/plugin-react'

// In dev the browser calls /api/* on localhost and Vite forwards it to the real
// API, which avoids CORS problems. Production builds call VITE_API_BASE_URL directly.
const target = process.env.VITE_API_PROXY_TARGET || 'https://api.forky.ca'

export default defineConfig({
  plugins: [react()],
  server: {
    proxy: {
      // Origin is dropped so the API's origin allow-list (assistant site mode) doesn't reject localhost in dev.
      '/api': { target: target, changeOrigin: true, secure: true, configure: (proxy) => proxy.on('proxyReq', (req) => req.removeHeader('origin')) },
      // Crawler files are generated by the API (see "Serving the files from the website's own address").
      ...Object.fromEntries(['/robots.txt', '/sitemap.xml', '/llms.txt', '/llms-full.txt', '/manifest.webmanifest'].map((p) => [p, { target, changeOrigin: true, secure: true, rewrite: () => `/api/v1/public/site${p}` }])),
    },
  },
})
